@dp.callback_query(F.data == "get_ticket")
async def get_ticket(callback: CallbackQuery):
    user_id = callback.from_user.id
    username = callback.from_user.username or "NoUsername"
    
    conn = sqlite3.connect("exam_final.db")
    cursor = conn.cursor()
    
    cursor.execute("SELECT status FROM users WHERE user_id = ?", (user_id,))
    user = cursor.fetchone()
    if not user or user[0] != "allowed":
        await callback.answer("У вас нет активного допуска к экзамену!", show_alert=True)
        conn.close()
        return
        
    cursor.execute("UPDATE users SET status = 'blocked' WHERE user_id = ?", (user_id,))
    conn.commit()
    
    categories = ["liqueur", "coffee", "anise", "strong", "wine", "beer", "cider"]
    categories_names = {
        "liqueur": "1. Ликёры",
        "coffee": "2. Кофе",
        "anise": "3. Анисовый алкоголь",
        "strong": "4. Крепкий алкоголь",
        "wine": "5. Вино",
        "beer": "6. Пиво",
        "cider": "7. Медовуха и Сидр"
    }
    
    selected_questions = []
    
    for cat in categories:
        cursor.execute("""
            SELECT id, text, answer FROM questions 
            WHERE category = ? AND id NOT IN (SELECT question_id FROM history WHERE user_id = ?)
            ORDER BY RANDOM() LIMIT 1
        """, (cat, user_id))
        
        q = cursor.fetchone()
        
        if not q:
            cursor.execute("DELETE FROM history WHERE user_id = ? AND question_id IN (SELECT id FROM questions WHERE category = ?)", (user_id, cat))
            conn.commit()
            cursor.execute("SELECT id, text, answer FROM questions WHERE category = ? ORDER BY RANDOM() LIMIT 1", (cat,))
            q = cursor.fetchone()
            
        if q:
            selected_questions.append(q)
            cursor.execute("INSERT INTO history (user_id, question_id) VALUES (?, ?)", (user_id, q[0]))
            
    conn.commit()
    conn.close()
    
    ticket_text = f"🔥 **ВАШ ЭКЗАМЕНАЦИОННЫЙ БИЛЕТ** 🔥\n" \
                  f"Студент: {callback.from_user.full_name}\n" \
                  f"⏱ На подготовку: 5 минут (сообщение удалится!)\n\n"
                  
    admin_text = f"👤 **Студент вытянул билет!**\n" \
                 f"Имя: {callback.from_user.full_name}\n" \
                 f"Юзернейм: @{username} (ID: `{user_id}`)\n\n" \
                 f"📝 **Вопросы в билете:**\n\n"
                 
    answers_text = f"🔑 **ШПАЛГАЛКА: ОТВЕТЫ К БИЛЕТУ** 🔑\n" \
                   f"Студент: {callback.from_user.full_name}\n\n"
                 
    for i, (q_id, q_text, q_ans) in enumerate(selected_questions):
        cat_code = categories[i]
        cat_name = categories_names[cat_code]
        
        ticket_text += f"📍 **{cat_name}**\n— {q_text}\n\n"
        admin_text += f"📍 **{cat_name}**\n— {q_text}\n\n"
        answers_text += f"📍 **{cat_name}**\n❓ *Вопрос:* {q_text}\n💡 *Ответ:* {q_ans}\n\n"
        
    await callback.message.edit_reply_markup(reply_markup=None)
    
    student_msg = await callback.message.answer(ticket_text, protect_content=True)
    
    for admin_id in ADMIN_IDS:
        try:
            admin_keyboard = InlineKeyboardMarkup(inline_keyboard=[
                [InlineKeyboardButton(text="🔄 Разрешить пересдачу", callback_data=f"reset_{user_id}")]
            ])
            await bot.send_message(chat_id=admin_id, text=admin_text, reply_markup=admin_keyboard)
            await bot.send_message(chat_id=admin_id, text=answers_text)
        except Exception as e:
            print(f"Не удалось отправить уведомления админу {admin_id}: {e}")
            
    await callback.answer("Билет получен!", show_alert=True)
    
    await asyncio.sleep(TIME_TO_PREPARE)
    try:
        await bot.delete_message(chat_id=user_id, message_id=student_msg.message_id)
        await bot.send_message(chat_id=user_id, text="⏱ **Время вышло!**\nБилет удален у вас с экрана. Начинайте устный ответ преподавателю.")
    except Exception:
        pass

